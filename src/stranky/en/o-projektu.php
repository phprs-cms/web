		<h2>Simplicity over abstraction</h2>
		<p>phpRS is written in plain PHP with no framework and not a single third-party library. It has no Composer, no npm and no build step. The reason is not nostalgia but longevity: code without dependencies does not become obsolete along with someone else's project, it can be read in full, and it runs on hosting that costs a few euros a month.</p>
		<p>The measure is simple – an informed non-programmer should be able to read and understand the source code. When a solution requires a layer that has to be studied first, we look for a different solution.</p>

		<h2>Extensions as a closed set</h2>
		<p>Most compromised content management systems did not fall because of the core, but because of a third-party plug-in. That is why phpRS has no third-party plug-ins. Less common features – polls, news items, the advertising system and others – are part of the package, have passed the same review as the core and are switched on in the settings.</p>
		<p>What the set does not cover is handled by a custom template, webhooks and the API.</p>

		<h2>Reader privacy</h2>
		<p>Traffic statistics are built in, with no cookies and no storing of IP addresses. Embedded videos and social media posts load only after a click. The antispam works without third-party services. A site on phpRS can be run without a cookie banner.</p>
		<p>The phpRS logo is never put on your site. The footers of the built-in templates carry only a discreet “powered by phpRS” note. It is your site.</p>

		<h2>Origin</h2>
		<p>phpRS takes its name from the Czech content management system phpRS of 2001–2007, but it is written from scratch and is not compatible with the original system.</p>

