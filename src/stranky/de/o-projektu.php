		<h2>Einfachheit vor Abstraktion</h2>
		<p>phpRS ist in reinem PHP geschrieben, ohne Framework und ohne eine einzige fremde Bibliothek. Es hat weder Composer noch npm noch einen Build-Schritt. Der Grund ist nicht Nostalgie, sondern Lebensdauer: Code ohne Abhängigkeiten veraltet nicht mit einem fremden Projekt, lässt sich vollständig lesen und läuft auf einem Hosting für wenige Euro im Monat.</p>
