		<h2>Erweiterungen als geschlossener Satz</h2>
		<p>Die meisten angegriffenen Redaktionssysteme sind nicht wegen des Kerns gefallen, sondern wegen eines Plug-ins von Dritten. phpRS hat deshalb keine fremden Plug-ins. Seltener benötigte Funktionen – Umfragen, Kurzmeldungen, das Anzeigensystem und weitere – gehören zum Paket, haben dieselbe Prüfung durchlaufen wie der Kern und werden in den Einstellungen eingeschaltet.</p>
		<p>Was im Satz fehlt, lösen eine eigene Vorlage, Webhooks und die API.</p>

		<h2>Privatsphäre der Leser</h2>
		<p>Die Besucherstatistik ist eine eigene, ohne Cookies und ohne Speicherung von IP-Adressen. Eingebettete Videos und Beiträge aus sozialen Netzwerken laden erst nach einem Klick. Der Spamschutz kommt ohne fremde Dienste aus. Eine Website mit phpRS lässt sich ohne Cookie-Banner betreiben.</p>
		<p>Auf Websites, die mit phpRS laufen, erscheint die Marke phpRS nicht. Es ist Ihre Website.</p>

